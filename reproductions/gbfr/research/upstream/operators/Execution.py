class PoTGenerationOperator:
    def __init__(self, config=None):
        self.llm_name = config['model_name'] if config else "openai"
        if config is None:
            self.llm = create_llm()
        else:
            self.llm = create_llm(self.llm_name)
        self.generated_programs = {}

    def _build_peo_from_formula_user_prompt(self, indicator_name: str, formula_expr: str = None,
                                            required_vars: List[str] = None) -> str:
        return f"""Please generate calculation code for the following financial indicator:

Indicator name: {indicator_name}
Calculation formula: {formula_expr}
Required variables: {required_vars}

Please generate the complete compute(vars) function:
    """

    def generate_from_formula(self, *, indicator_name: str = None, formula_expr: str = None,
                              formula_code: str = None, required_vars: List[str] = None,
                              path_id: int = 0, max_retries: int = 2) -> PoTProgram:
        _indicator_name = indicator_name or ''
        _formula_expr = formula_expr or ''
        _reference_code = formula_code or ''
        _required_vars = required_vars or []
        required_vars_desc = str(_required_vars)

        prompt = self._build_peo_from_formula_user_prompt(_indicator_name, _formula_expr, required_vars_desc)

        program_code = None
        is_valid = False
        error_msg = None

        for attempt in range(max_retries + 1):
            if attempt > 0:
                retry_prompt = prompt + f"\n\nNote: The previously generated code had an error ({error_msg}). Please ensure the code is complete and syntactically correct."
            else:
                retry_prompt = prompt

            response = self.llm.invoke(retry_prompt, system_prompt=PROGRAM_GENERATION_FROM_FORMULA_PROMPT).content
            program_code = self._extract_code_block(response)

            if not program_code:
                program_code = response

            is_valid, error_msg = self._validate_code(program_code)
            if is_valid:
                break

        notes = f"Generated by {self.llm_name} about {indicator_name}" + (
            f", validation error: {error_msg}" if not is_valid else "")

        pot_program = PoTProgram(
            path_id=path_id,
            indicator_name=_indicator_name,
            formula_expr=_formula_expr,
            required_vars=_required_vars,
            program=program_code,
            reference_code=_reference_code,
            notes=notes
        )

        cache_key = f"{_indicator_name}_{path_id}"
        self.generated_programs[cache_key] = pot_program
        return pot_program

    def _extract_code_block(self, text: str, language: str = "python") -> Optional[str]:
        if not text:
            return None

        pattern = rf"```{language}\s*\n?([\s\S]*?)```"
        match = re.search(pattern, text, re.IGNORECASE)
        if match:
            code = match.group(1).strip()
            return self._clean_code(code)

        pattern = r"```\s*\n?([\s\S]*?)```"
        match = re.search(pattern, text)
        if match:
            code = match.group(1).strip()
            return self._clean_code(code)

        if "def compute" in text:
            start_idx = text.find("def compute")
            if start_idx != -1:
                code = text[start_idx:]
                return self._clean_code(code)
        return None

    def _clean_code(self, code: str) -> str:
        if not code:
            return code
        lines = code.split('\n')
        cleaned_lines = []
        for line in lines:
            stripped = line.strip()
            if stripped.startswith('import ') or stripped.startswith('from '):
                continue
            if stripped.startswith('```'):
                continue
            cleaned_lines.append(line)
        return '\n'.join(cleaned_lines)

    def _validate_code(self, code: str) -> tuple:
        try:
            compile(code, '<string>', 'exec')
            if 'def compute' not in code:
                return False, "compute function not defined in code"
            return True, None
        except SyntaxError as e:
            return False, f"Syntax error: {e}"
        except Exception as e:
            return False, f"Validation error: {e}"

    def _build_peo_for_solve_user_prompt(self, query: str = None, context: str = None,
                                         reasoning_type: str = None, evidences: str = None,
                                         formula_expr: str = None, explanation: str = None,
                                         precision: str = None):
        prompt = f"""Please generate calculation code according to following information:

Question: {query}

Context: {context}

Reasoning type: {reasoning_type}

Evidences (IMPORTANT - use these exact variable names as keys in vars dict):
{evidences}"""

        if formula_expr:
            prompt = prompt + f"\nMetric formula: {formula_expr}"

        if explanation:
            prompt = prompt + f"\nConcept explanation: {explanation}"

        if precision:
            prompt = prompt + f"\nPrecision requirement: {precision}"

        prompt += """

CRITICAL: The vars dict will contain keys exactly as shown in the evidences above (e.g., "v1", "v2", etc.).
You MUST use these exact keys to access values. For example: vars["v1"], vars["v2"], etc.
DO NOT use metric names as keys - use the var_name (v1, v2, ...) as keys.

Please generate the complete compute(vars) function:"""

        return prompt

    def _build_peo_for_solve_problem(self, query: str = None, context: str = None,
                                     reasoning_type: str = None, evidences: str = None,
                                     formula_expr: str = None, explanation: str = None,
                                     precision: str = None):
        prompt = f"""Please give the result of query according to following information, thinking step by step:

Question: {query}

Context: {context}

Reasoning type: {reasoning_type}

Evidences :
{evidences}"""

        if formula_expr:
            prompt = prompt + f"\nMetric formula: {formula_expr}"

        if explanation:
            prompt = prompt + f"\nConcept explanation: {explanation}"

        if precision:
            prompt = prompt + f"\nPrecision requirement: {precision}"

        prompt += """

CRITICAL: ONLY return the result. DO NOT explanation."""

        return prompt

    def generate_for_solve(self, query: str = None, context: str = None,
                           reasoning_type: str = None, evidences: EvidenceSeekingOutput = None,
                           formula_expr: str = None, explanation: str = None,
                           precision: str = None, max_retries: int = 2) -> PoTProgram:
        evidences_str = self._evidence_to_lines(evidences)
        prompt = PROGRAM_GENERATION_FOR_QUERY_PROMPT + self._build_peo_for_solve_user_prompt(
            query, context, reasoning_type, evidences_str, formula_expr, explanation, precision)

        program_code = None
        is_valid = False
        error_msg = None

        for attempt in range(max_retries + 1):
            if attempt > 0:
                retry_prompt = prompt + f"\n\nNote: The previously generated code: {program_code} \n It had an error ({error_msg}). Please ensure the code is complete and syntactically correct."
            else:
                retry_prompt = prompt

            response = self.llm.invoke(retry_prompt).content
            program_code = self._extract_code_block(response)

            if not program_code:
                program_code = response

            is_valid, error_msg = self._validate_code(program_code)
            if is_valid:
                break

        notes = f"Generated by {self.llm_name} for question" + (
            f", validation error: {error_msg}" if not is_valid else "")

        required_vars = list(evidences.var_bindings.keys()) if evidences and evidences.var_bindings else []

        pot_program = PoTProgram(
            path_id=0,
            program=program_code,
            required_vars=required_vars,
            notes=notes
        )

        cache_key = "final_0"
        self.generated_programs[cache_key] = pot_program
        return pot_program

    def generate_for_solve_with_retry(self, query: str = None, context: str = None,
                                      reasoning_type: str = None, evidences: EvidenceSeekingOutput = None,
                                      formula_expr: str = None, explanation: str = None,
                                      precision: str = None, previous_code: str = None,
                                      execution_error: str = None) -> PoTProgram:
        evidences_str = self._evidence_to_lines(evidences)

        base_prompt = self._build_peo_for_solve_user_prompt(
            query, context, reasoning_type, evidences_str, formula_expr, explanation, precision)

        if previous_code and execution_error:
            retry_prompt = f"""
Previous code failed with error:

Code:
{previous_code}

Error:
{execution_error}

Common fixes:
- KeyError: Check dictionary key names, use vars["var1"] not vars["metric_name"]
- ZeroDivisionError: Add zero check before division
- TypeError: Check data type conversions

Please fix the error and regenerate the code.
"""
            prompt = PROGRAM_GENERATION_FOR_QUERY_PROMPT + base_prompt + retry_prompt
        else:
            prompt = PROGRAM_GENERATION_FOR_QUERY_PROMPT + base_prompt

        response = self.llm.invoke(prompt).content
        program_code = self._extract_code_block(response)

        if not program_code:
            program_code = response

        is_valid, error_msg = self._validate_code(program_code)
        notes = f"Generated by {self.llm_name} for question (retry)" + (
            f", validation error: {error_msg}" if not is_valid else "")

        required_vars = list(evidences.var_bindings.keys()) if evidences and evidences.var_bindings else []

        return PoTProgram(
            path_id=0,
            program=program_code,
            required_vars=required_vars,
            notes=notes
        )

    def solve_problem(self, query: str = None, context: str = None,
                      reasoning_type: str = None, evidences: EvidenceSeekingOutput = None,
                      formula_expr: str = None, explanation: str = None,
                      precision: str = None, path_id: int = 0, max_retries: int = 2) -> PoTExecutionResult:
        evidences_str = self._evidence_to_lines(evidences)
        prompt = ANSWER_GENERATION_FOR_QUERY_PROMPT + self._build_peo_for_solve_problem(
            query, context, reasoning_type, evidences_str, formula_expr, explanation, precision)
        value = self.llm.invoke(prompt).content

        return PoTExecutionResult(
            path_id=path_id, ok=True, value=value, trace={}, program=''
        )

    def _evidence_to_lines(self, evidence: EvidenceSeekingOutput) -> str:
        if evidence is None or not evidence.var_bindings:
            return "No evidence available"

        lines: List[str] = []

        for var_name, item in evidence.var_bindings.items():
            c = item.constraints
            meta = c.meta

            parts = []
            parts.append(f'temporal_scope="{c.temporal_scope or "unknown"}"')
            parts.append(f'entity_scope="{c.entity_scope or "unknown"}"')
            if meta.currency is not None:
                parts.append(f'meta.currency="{meta.currency}"')
            if meta.scale is not None:
                parts.append(f'meta.scale="{meta.scale}"')
            if meta.unit is not None:
                parts.append(f'meta.unit="{meta.unit}"')

            constraints_str = ", ".join(parts)

            snippet = item.context.strip() if item.context else ""
            lines.append(
                f'- KEY TO USE IN CODE: "{var_name}" (use vars["{var_name}"] to access)\n'
                f'  metric description: "{item.metric}"\n'
                f'  constraints: {constraints_str}\n'
                f'  value: {item.value}\n'
                f'  evidence snippet: {repr(snippet[:100]) if snippet else "N/A"}\n'
                f'  confidence: {item.confidence}'
            )

        return "\n".join(lines)


class PoTExecutor:
    def __init__(self, timeout: int = 10, lang: str = "zh"):
        self.timeout = timeout
        self.lang = lang
        self.execution_history: List[PoTExecutionResult] = []

    def run(self, program: str, var_values: Dict[str, float], path_id: int = 0) -> PoTExecutionResult:
        program = self._preprocess_code(program)

        if not program or 'def compute' not in program:
            error_msg = "Invalid code or compute function not defined"
            return PoTExecutionResult(
                path_id=path_id, ok=False,
                error=error_msg, program=program
            )

        try:
            local_env = {
                '__builtins__': {
                    'abs': abs, 'min': min, 'max': max, 'sum': sum,
                    'round': round, 'pow': pow, 'len': len,
                    'float': float, 'int': int, 'str': str,
                    'dict': dict, 'list': list, 'tuple': tuple,
                    'set': set, 'frozenset': frozenset,
                    'bool': bool, 'bytes': bytes,
                    'True': True, 'False': False, 'None': None,
                    'isinstance': isinstance, 'issubclass': issubclass,
                    'type': type, 'hasattr': hasattr, 'getattr': getattr,
                    'setattr': setattr, 'callable': callable,
                    'range': range, 'enumerate': enumerate, 'zip': zip,
                    'map': map, 'filter': filter, 'sorted': sorted,
                    'reversed': reversed, 'any': any, 'all': all,
                    'Exception': Exception, 'ValueError': ValueError,
                    'ZeroDivisionError': ZeroDivisionError,
                    'KeyError': KeyError, 'TypeError': TypeError,
                    'IndexError': IndexError, 'AttributeError': AttributeError,
                }
            }

            import math
            local_env['math'] = math

            exec(program, local_env)

            if 'compute' not in local_env:
                error_msg = "compute function not defined in code"
                return PoTExecutionResult(
                    path_id=path_id, ok=False,
                    error=error_msg, program=program
                )

            result = local_env['compute'](var_values)

            if isinstance(result, dict):
                value = result.get('value')
                trace = result.get('trace', {})
            else:
                value = float(result)
                trace = {}

            execution_result = PoTExecutionResult(
                path_id=path_id, ok=True, value=value, trace=trace, program=program
            )

        except ZeroDivisionError:
            error_msg = "Division by zero error"
            execution_result = PoTExecutionResult(
                path_id=path_id, ok=False, error=error_msg, program=program
            )
        except KeyError as e:
            error_msg = f"Missing variable: {e}"
            execution_result = PoTExecutionResult(
                path_id=path_id, ok=False, error=error_msg, program=program
            )
        except Exception as e:
            execution_result = PoTExecutionResult(
                path_id=path_id, ok=False, error=str(e), program=program
            )

        self.execution_history.append(execution_result)
        return execution_result

    def _preprocess_code(self, code: str) -> str:
        if not code:
            return code
        lines = code.split('\n')
        cleaned_lines = []
        for line in lines:
            stripped = line.strip()
            if stripped.startswith('import ') or stripped.startswith('from '):
                continue
            if stripped.startswith('```'):
                continue
            cleaned_lines.append(line)
        return '\n'.join(cleaned_lines)