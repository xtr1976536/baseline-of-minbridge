"""Build a credential-free GBFR delivery snapshot without changing originals."""
from collections import Counter
from datetime import datetime,timezone,timedelta
import hashlib
import json
import os
from pathlib import Path
import re
import zipfile

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'deliverables/GBFR_R25_20261108'
ARCHIVE=OUT/'GBFR_complete_R25_20261108_final.zip'
DIRECTORIES=['gbfr','configs','data','docs','research','runs','scripts','tests']
ROOT_FILES=['README.md','pyproject.toml','requirements.lock.txt','.gitignore','.env.example']
SKIP_DIRS={'.git','.venv','venv','__pycache__','.pytest_cache','node_modules','gbfr_paper.egg-info'}
TEXT_SUFFIX={'.py','.txt','.md','.json','.jsonl','.toml','.yaml','.yml','.ini','.cfg','.env','.example','.log','.csv','.tsv','.lock','.ps1','.bat','.sh'}
SECRET_PATTERNS=[re.compile(rb'\bsk-[A-Za-z0-9_-]{20,}\b'),
    re.compile(rb'\b(?:gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,})\b'),
    re.compile(rb'(?i)(?:[\x22\x27]?)(?:api[_-]?key|access[_-]?token|auth[_-]?token|client[_-]?secret|password)[\x22\x27]?\s*[:=]\s*[\x22\x27]([A-Za-z0-9_./+=-]{20,})[\x22\x27]')]
FAKE=(b'sk-test',b'sk-fake',b'sk-dummy',b'sk-example',b'sk-your',b'sk-redacted')
PLACEHOLDER=(b'your_',b'example',b'placeholder',b'not-a-real',b'os.environ',b'GBFR_',b'TEST_')

def digest(data):return hashlib.sha256(data).hexdigest()

def sanitize(data,path):
    changes=[]
    for pattern in SECRET_PATTERNS:
        def replace(match):
            token=match.group(1) if match.lastindex else match.group(0)
            if token.lower().startswith(FAKE) or any(s.lower() in token.lower() for s in PLACEHOLDER):return match.group(0)
            changes.append({'kind':'credential-like literal','bytes':len(token)})
            return match.group(0).replace(token,b'[REDACTED_CREDENTIAL]')
        data=pattern.sub(replace,data)
    return data,changes

def selected_files():
    items=[];excluded=[]
    for name in ROOT_FILES:
        p=ROOT/name
        if p.exists():items.append((p,name))
    for name in DIRECTORIES:
        start=ROOT/name
        if not start.exists():continue
        for folder,dirs,files in os.walk(start):
            dirs[:]=[d for d in dirs if d not in SKIP_DIRS and not (Path(folder)/d).is_symlink() and not (Path(folder)/d).is_junction()]
            for filename in files:
                p=Path(folder)/filename;rel=p.relative_to(ROOT).as_posix()
                reason=None
                if p.is_symlink():reason='symbolic link'
                elif p.suffix in {'.pyc','.pyo','.p12','.pfx','.pem','.key'}:reason='generated bytecode or private-key container'
                elif filename.startswith('.env') and filename!='.env.example':reason='local environment credentials'
                elif p.parent==ROOT/'configs' and filename.startswith('local'):reason='local-only configuration'
                if reason:excluded.append({'path':rel,'reason':reason})
                else:items.append((p,rel))
    paper=Path('D:/腾讯电脑管家软件搬家/C盘清理文件搬家/xwechat_files/wxid_hfv3pp323yhi22_0c7f/temp/RWTemp/2026-11/1f2a8ad4c3bcb4720bb35264ac044ce9/2026.acl-long.1273.pdf')
    if paper.exists():items.append((paper,'materials/paper/2026.acl-long.1273.pdf'))
    return sorted(items,key=lambda x:x[1]),excluded

def main():
    OUT.mkdir(parents=True,exist_ok=True)
    if ARCHIVE.exists():raise RuntimeError('Delivery archive already exists; preserve it')
    files,excluded=selected_files();manifest=[];redactions=[];prefix='GBFR_R25_20261108/'
    started=datetime.now(timezone(timedelta(hours=8))).isoformat()
    readme='''GBFR 最新完整资料包（2026-11-08，Asia/Shanghai）

入口：README.md 和 docs/FINQA_FRESH_R25_20261107.md。
本包包含当前代码、依赖锁、测试、完整冻结数据/图谱、论文与上游来源、全部GBFR实验/缓存/失败记录、版本快照和最新审计。
R25仅运行全新FinQA10题，TAT-QA未重跑；全量仍暂停，旧R19为1401条记录。
原先冻结评分为固定两位50%／参考显示精度60%；单位解析修正对同一预测的运行后诊断为60%／70%，原记录均保留。
拒答召回50%(1/2)，误拒0/8，技术错误0；430项测试通过，不能宣称已全面达到论文指标。

安装：Python3.11+；python -m pip install -c requirements.lock.txt -e ".[test]"
离线检查：python -m pytest -q
API凭据必须由接收者自行在环境变量中设置，本包不包含真实API密钥；不要从旧运行断点自动恢复全量。

PACKAGE_MANIFEST.json 记录打包文件的原始与交付SHA-256、大小、必要脱敏与排除项。历史配置保留原机器路径，作为审计快照；当前入口的路径由解压后工作区解析。
未包含可重新生成的.git、虚拟环境、字节码、构建/临时目录；同目录独立FINDER/VeriFin/finance_reasoning项目不属于本次GBFR交付。
'''
    with zipfile.ZipFile(ARCHIVE,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=9,allowZip64=True) as z:
        z.writestr(prefix+'DELIVERY_README_请先阅读.txt',readme)
        for i,(p,rel) in enumerate(files):
            before=p.stat();data=p.read_bytes();after=p.stat()
            if (before.st_size,before.st_mtime_ns)!=(after.st_size,after.st_mtime_ns):raise RuntimeError('Source changed while reading: '+rel)
            original=digest(data)
            if re.search(rb'(?m)^-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----\r?$',data):
                excluded.append({'path':rel,'reason':'private key block'});continue
            safe,changes=sanitize(data,p)
            if changes and p.suffix.lower() not in TEXT_SUFFIX:
                excluded.append({'path':rel,'reason':'credential-like bytes in non-text file'});continue
            if changes:redactions.append({'path':rel,'changes':changes})
            z.writestr(prefix+rel,safe)
            manifest.append({'path':rel,'bytes':len(safe),'source_sha256':original,'packaged_sha256':digest(safe),'redacted':bool(changes)})
            if i and i%4000==0:print(json.dumps({'stage':'packing','files':i,'of':len(files)}),flush=True)
        record={'created_at':started,'project':'GBFR','revision':'R25 with separately preserved post-hoc scorer correction',
            'recipient':'tongrenxiao7@gmail.com','included_files':len(manifest),'included_uncompressed_bytes':sum(x['bytes'] for x in manifest),
            'scope_roots':DIRECTORIES+ROOT_FILES,'excluded_workspace_projects':['finder','verifin','finance_reasoning'],
            'excluded_regenerable_directories':sorted(SKIP_DIRS|{'build','tmp'}),'excluded_files':excluded,'redactions':redactions,
            'full_experiment_paused':json.loads((ROOT/'runs/gpt56_sol_full_r19/control.json').read_text(encoding='utf-8'))['paused'],
            'files':manifest}
        z.writestr(prefix+'PACKAGE_MANIFEST.json',json.dumps(record,ensure_ascii=False,indent=2))
    with zipfile.ZipFile(ARCHIVE) as z:
        bad=z.testzip()
        if bad:raise RuntimeError('ZIP integrity failed: '+bad)
        names=set(z.namelist())
        for required in ['gbfr/engine.py','gbfr/metrics.py','gbfr/units.py','data/main/FinQA.jsonl','data/assets/fmkg.reconstructed_candidate_v2_conservative.json','runs/gbfr_e2e_validation/r25/results.json','research/repairs/20261107/r25_scoring_correction.json','docs/FINQA_FRESH_R25_20261107.md']:
            if prefix+required not in names:raise RuntimeError('Required material missing: '+required)
    archive_sha=hashlib.sha256();archive_md5=hashlib.md5()
    with ARCHIVE.open('rb') as f:
        for chunk in iter(lambda:f.read(1024*1024),b''):archive_sha.update(chunk);archive_md5.update(chunk)
    result={'archive':str(ARCHIVE),'bytes':ARCHIVE.stat().st_size,'sha256':archive_sha.hexdigest(),'md5':archive_md5.hexdigest(),
        'files':len(manifest)+2,'source_bytes':sum(x['bytes'] for x in manifest),'redacted_files':redactions,'excluded_file_count':len(excluded),'zip_crc_verified':True}
    (OUT/'package_summary.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    (OUT/'SHA256SUMS.txt').write_text(result['sha256']+'  '+ARCHIVE.name+'\n',encoding='ascii')
    print(json.dumps(result,ensure_ascii=False),flush=True)

if __name__=='__main__':main()
